// Google Maps consumes these as native bitmaps, avoiding Android Fabric's
// legacy custom-marker shadow-node sizing path in react-native-maps 1.20.1.
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');
function pure(file) {
  const module = { exports: {} };
  const output = ts.transpileModule(fs.readFileSync(path.join(root, file), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  new Function('module', 'exports', output)(module, module.exports);
  return module.exports;
}
const { symbolPaths } = pure('src/components/world-window/dreams/placeSymbols.ts');
const { colors } = pure('src/theme/trotterTheme.ts');
const fontfile = path.join(root, 'assets/world-window/fonts/DMSans-SemiBold.ttf');
const keys = [...Object.keys(symbolPaths), 'area', ...Array.from({ length: 98 }, (_, i) => `count-${i + 2}`), 'count-99plus'];
const size = 40; // 36 dp circle plus a transparent 2 dp anti-aliasing margin.
async function renderMarker(key, selected, scale) {
  const count = key.startsWith('count-') ? key.slice(6).replace('plus', '+') : undefined;
  const fill = selected ? '#995e3d' : colors.ink;
  const border = selected ? 3 : 2;
  const outline = key === 'area' ? ' stroke-dasharray="5 3"' : '';
  const symbol = key === 'area'
    ? '<circle cx="12" cy="12" r="9"/><ellipse cx="12" cy="12" rx="4" ry="9"/><path d="M3 12h18M5 6.5q7 4 14 0M5 17.5q7-4 14 0"/>'
    : (symbolPaths[key] ?? []).map(d => `<path d="${d}"/>`).join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${size * scale}" height="${size * scale}" viewBox="0 0 ${size} ${size}">
    <circle cx="20" cy="20" r="${18 - border / 2}" fill="${fill}" stroke="${colors.paper}" stroke-width="${border}"${outline}/>
    <g transform="translate(10 10) scale(${20 / 24})" fill="none" stroke="${colors.paper}" stroke-width="${key === 'area' ? 1.6 : 1.4}" stroke-linecap="round" stroke-linejoin="round">${symbol}</g>
  </svg>`;
  let image = sharp(Buffer.from(svg));
  if (count) {
    const label = await sharp({ text: { text: `<span foreground="${colors.paper}">${count}</span>`, font: `DM Sans SemiBold ${count.length > 2 ? 11 : 13}`, fontfile, dpi: 72 * scale, rgba: true } }).png().toBuffer();
    image = image.composite([{ input: label, gravity: 'centre' }]);
  }
  return image.png({ compressionLevel: 9 }).toBuffer();
}
async function build() {
  const directory = path.join(root, 'assets/world-window/dreams/map-markers');
  fs.mkdirSync(directory, { recursive: true });
  const entries = [];
  for (const key of keys) {
    for (const selected of [false, true]) for (const scale of [1, 2, 3]) {
      const name = `${key}${selected ? '-selected' : ''}${scale > 1 ? `@${scale}x` : ''}.png`;
      fs.writeFileSync(path.join(directory, name), await renderMarker(key, selected, scale));
    }
    entries.push(`  '${key}': [require('../../../assets/world-window/dreams/map-markers/${key}.png'), require('../../../assets/world-window/dreams/map-markers/${key}-selected.png')],`);
  }
  const manifest = `// Generated by scripts/buildDreamMapMarkers.cjs. Do not edit by hand.\nimport type { ImageRequireSource } from 'react-native';\n\nexport const dreamMarkerImages: Record<string, readonly [ImageRequireSource, ImageRequireSource]> = {\n${entries.join('\n')}\n};\n`;
  fs.writeFileSync(path.join(root, 'src/assets/generated/dreamMarkerManifest.ts'), manifest);
  console.log(`Generated ${keys.length * 2 * 3} density-aware map marker assets from the app's existing vectors and typography.`);
}
module.exports = { keys, size, renderMarker };
if (require.main === module) build().catch(error => { console.error(error); process.exitCode = 1; });
